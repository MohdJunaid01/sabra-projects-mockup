// Helper to look up any material by ID
export function getMaterialById(id) {
  return ALL_MATERIALS.find(m => m.id === id) || TIMBER_MATERIALS.find(t => t.id === id) || TIMBER_MATERIALS[0];
}

// Backward compatibility helper
export function getTimberById(id) {
  return getMaterialById(id);
}
